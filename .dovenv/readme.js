import { defineConfig } from '@dovenv/core'

import { coreOpts } from './core.js'

export default defineConfig(
	{
		custom : {
			readme : {
				desc : 'Readme file',
				fn   : async props => {

					const {
						joinPath,
						writeFile,
						readFile,
						relativePath,
					} = await import( '@dovenv/core/utils' )

					const output        = joinPath( coreOpts.workspaceDir, './README.md' )
					const input         = joinPath( coreOpts.coreDir, './README.md' )
					const inputRelative = relativePath( props.utils.process.cwd(), input )
					const content       = await readFile( input )

					await writeFile( output, `<!-- 
  WARNING: DO NOT EDIT THIS FILE DIRECTLY.
  This file is automatically generated as a copy of "${inputRelative}".
  Any changes made here will be overwritten. Please edit the source file at 
  "${inputRelative}" instead.
-->
${content}` )
					props.utils.log.success( 'README copied!' )

				},
			},
		},
	},
)
