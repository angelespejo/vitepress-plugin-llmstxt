import { defineConfig } from '@dovenv/core'
import {
	pigeonposseMonorepoTheme,
	getWorkspaceConfig,
} from '@dovenv/theme-pigeonposse'

const corePath = './packages/plugin'

export default defineConfig(
	{
		custom : {
			readme : {
				desc : 'Readme file',
				fn   : async props => {

					const {
						joinPath,
						writeFile,
						readFile,
						relativePath,
					} = await import( '@dovenv/core/utils' )

					const output        = joinPath( props.utils.wsDir, './README.md' )
					const input         = joinPath( props.utils.wsDir, corePath, './README.md' )
					const inputRelative = relativePath( props.utils.process.cwd(), input )
					const content       = await readFile( input )

					await writeFile( output, `<!-- 
  WARNING: DO NOT EDIT THIS FILE DIRECTLY.
  This file is automatically generated as a copy of "${inputRelative}".
  Any changes made here will be overwritten. Please edit the source file at 
  "${inputRelative}" instead.
-->
${content}` )
					props.utils.log.success( 'README copied!' )

				},
			},
		},
	},
	pigeonposseMonorepoTheme( {
		repo : {
			commit : {
				scopes : [
					{
						value : 'all',
						title : 'All',
						desc  : 'All: packages + environment',
					},
					{
						value : 'package',
						title : 'Packages',
						desc  : 'Package(s) only',
					},
					{
						value : 'env',
						title : 'Environment',
						desc  : 'Only development environment',
					},
				],
			},
		},
		lint : { publint: { pkg: { pkgDir: '.' } } },
		core : await getWorkspaceConfig( {
			metaURL : import.meta.url,
			path    : '../',
			corePath,
		} ),
	} ),
)
